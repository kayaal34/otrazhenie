-- =========================================================================
-- Патч 012: на самом деле включает автоматическое снятие истёкших
-- удержаний слотов (release_expired_holds()) через pg_cron — раз в минуту.
--
-- Причина бага «холд не снимается через 15 минут»: release_expired_holds()
-- существовала с самого начала (см. schema.sql), но её вызов по расписанию
-- был описан только как ручная инструкция в комментарии внизу schema.sql
-- («Примечание по эксплуатации») — её никто не выполнял отдельно. То есть
-- функция была написана, но никогда не запускалась сама по себе.
--
-- Если выполнение упадёт с ошибкой доступа к расширению pg_cron — сначала
-- включите его через Supabase Dashboard → Database → Extensions → pg_cron,
-- затем выполните этот патч ещё раз.
--
-- Безопасно выполнять повторно (снимает старое задание с тем же именем
-- перед тем, как создать новое).
-- =========================================================================

create extension if not exists pg_cron with schema pg_catalog;

select cron.unschedule(jobid) from cron.job where jobname = 'release-expired-holds';

select cron.schedule(
  'release-expired-holds',
  '* * * * *',
  $$select release_expired_holds();$$
);
