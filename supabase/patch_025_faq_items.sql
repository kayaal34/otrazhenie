--
--   faq_items — вопросы/ответы с главной страницы. Публично читаются только
--   опубликованные (is_published), всё остальное — только админ (is_admin()).
--   Ответ — обычный текст; строки, начинающиеся с «- », на сайте
--   отображаются маркированным списком.
--
-- Стартовые данные — те же 9 вопросов, что раньше были зашиты в
-- src/lib/faqContent.tsx. Добавляются только если таблица пустая.
--
-- Безопасно выполнять повторно.
-- =========================================================================

create table if not exists faq_items (
  id uuid primary key default gen_random_uuid(),
  question text not null,
  answer text not null,
  sort_order int not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table faq_items enable row level security;

drop policy if exists "faq_items_public_read" on faq_items;
create policy "faq_items_public_read" on faq_items
  for select using (is_published = true or is_admin());

drop policy if exists "faq_items_admin_write" on faq_items;
create policy "faq_items_admin_write" on faq_items
  for all using (is_admin()) with check (is_admin());

